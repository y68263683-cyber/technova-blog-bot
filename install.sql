CREATE TABLE IF NOT EXISTS sources (
 id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(120) NOT NULL, url VARCHAR(2048) NOT NULL UNIQUE,
 category VARCHAR(30) NOT NULL DEFAULT 'world', active TINYINT(1) NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS raw_items (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, source_id INT NOT NULL, title VARCHAR(500) NOT NULL,
 link VARCHAR(2048) NOT NULL UNIQUE, summary TEXT, tokens TEXT, article_id BIGINT NULL,
 created_at DATETIME NOT NULL, INDEX(article_id), INDEX(source_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS articles (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, slug VARCHAR(220) UNIQUE, category VARCHAR(30) NOT NULL DEFAULT 'world',
 status VARCHAR(20) NOT NULL DEFAULT 'new', breaking TINYINT(1) NOT NULL DEFAULT 0,
 n_sources INT NOT NULL DEFAULT 1, tokens TEXT, hint VARCHAR(30),
 title_ar VARCHAR(500), title_en VARCHAR(500), title_fr VARCHAR(500),
 summary_ar MEDIUMTEXT, summary_en MEDIUMTEXT, summary_fr MEDIUMTEXT,
 seo_ar VARCHAR(500), seo_en VARCHAR(500), seo_fr VARCHAR(500), keywords VARCHAR(500),
 created_at DATETIME NOT NULL, published_at DATETIME NULL, INDEX(status,published_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS logs (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, ts DATETIME NOT NULL, kind VARCHAR(40), level VARCHAR(20), msg VARCHAR(1000)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS api_usage (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, ts DATETIME NOT NULL, provider VARCHAR(30), ok TINYINT(1), tokens INT DEFAULT 0
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS raw_item_images (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, raw_item_id BIGINT NOT NULL,
 image_url VARCHAR(1900) NOT NULL, INDEX(raw_item_id),
 UNIQUE KEY uniq_raw_image(raw_item_id,image_url(180))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS article_images (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, article_id BIGINT NOT NULL,
 image_url VARCHAR(1900) NOT NULL, source_name VARCHAR(120) DEFAULT NULL,
 INDEX(article_id), UNIQUE KEY uniq_article_image(article_id,image_url(180))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
